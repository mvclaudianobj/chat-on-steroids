import { app, ipcMain, type BrowserWindow } from 'electron';
import { spawn, type ChildProcess } from 'node:child_process';
import { promises as fs } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { z } from 'zod';
import type { VmAction, VmDoctor, VmJob, VmLab, VmView } from '../shared/vms.js';
import { markspanelAccessBlocked } from './markspanel-auth.js';

const nameSchema = z.string().regex(/^[a-z](?:[a-z0-9-]{0,38}[a-z0-9])?$/);
const boxSchema = z.string().regex(/^[a-zA-Z0-9][a-zA-Z0-9._/-]{1,120}$/).refine(v => !v.includes('..') && !v.includes('//'));
const actions: Record<VmAction, string[]> = {
  status: ['status'], up: ['up', '--provider=virtualbox'], halt: ['halt'],
  provision: ['provision'], destroy: ['destroy', '--force']
};
const request = z.discriminatedUnion('action', [
  z.object({ action: z.literal('view') }).strict(),
  z.object({ action: z.literal('init'), name: nameSchema, box: boxSchema, memory: z.number().int().min(512).max(32768), cpus: z.number().int().min(1).max(16) }).strict(),
  z.object({ action: z.literal('run'), name: nameSchema, op: z.enum(['status', 'up', 'halt', 'provision', 'destroy']), confirmation: z.string().max(40).optional(), dryRun: z.boolean().optional() }).strict(),
  z.object({ action: z.literal('cancel'), name: nameSchema }).strict()
]);
const jobs = new Map<string, { state: VmJob; process: ChildProcess | null; timer: NodeJS.Timeout | null }>();
const busy = new Set<string>();
const digest = (data: string): string => createHash('sha256').update(data).digest('hex');
const root = (): string => path.join(app.getPath('userData'), 'vms');
const labFolder = (name: string): string => path.join(root(), name);
const vagrantfile = (name: string, box: string, memory: number, cpus: number): string =>
  `# Generated by Chat Marks; no host sharing or forwarded ports.
Vagrant.configure("2") do |config|
  config.vm.box = "${box}"
  config.vm.hostname = "${name}.test"
  config.vm.synced_folder ".", "/vagrant", disabled: true
  config.ssh.insert_key = true
  config.vm.provider "virtualbox" do |provider|
    provider.name = "marks-${name}"
    provider.memory = ${memory}
    provider.cpus = ${cpus}
  end
  config.vm.provision "ansible" do |ansible|
    ansible.playbook = "site.yml"
  end
end
`;
const playbook = '---\n- name: Verify isolated Chat Marks guest\n  hosts: all\n  gather_facts: false\n  tasks:\n    - name: Confirm Ansible can reach the guest\n      ansible.builtin.ping: {}\n';
async function checkedRoot(create = false): Promise<void> {
  // VM folders live only inside Electron's own private profile, never a renderer-selected root.
  if (create) await fs.mkdir(root(), { recursive: true, mode: 0o700 });
  const stat = await fs.lstat(root());
  if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error('Invalid VM storage directory.');
}
async function openLab(name: string): Promise<{ directory: string; manifest: Record<string, unknown> }> {
  await checkedRoot();
  const directory = labFolder(name);
  const stat = await fs.lstat(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink()) throw new Error('Invalid VM directory.');
  const file = path.join(directory, 'lab.json');
  const info = await fs.lstat(file);
  if (!info.isFile() || info.isSymbolicLink()) throw new Error('Invalid VM manifest.');
  const manifest = JSON.parse(await fs.readFile(file, 'utf8')) as Record<string, unknown>;
  const details = z.object({
    schema: z.literal('chat-marks-vm-lab'), version: z.literal(1),
    name: nameSchema, box: boxSchema, memory: z.number().int().min(512).max(32768),
    cpus: z.number().int().min(1).max(16),
    files: z.object({ Vagrantfile: z.string().length(64), 'site.yml': z.string().length(64) })
  }).parse(manifest);
  if (details.name !== name) throw new Error('VM name mismatch.');
  const expected = { Vagrantfile: vagrantfile(name, details.box, details.memory, details.cpus), 'site.yml': playbook };
  for (const [filename, hash] of Object.entries(details.files)) {
    const target = path.join(directory, filename);
    const fileStat = await fs.lstat(target);
    if (!fileStat.isFile() || fileStat.isSymbolicLink() || digest(await fs.readFile(target, 'utf8')) !== hash || hash !== digest(expected[filename as keyof typeof expected])) throw new Error('VM template was modified.');
  }
  return { directory, manifest };
}
async function init(name: string, box: string, memory: number, cpus: number): Promise<void> {
  await checkedRoot(true);
  const directory = labFolder(name);
  await fs.mkdir(directory, { mode: 0o700 });
  const files = { Vagrantfile: vagrantfile(name, box, memory, cpus), 'site.yml': playbook };
  for (const [filename, contents] of Object.entries(files)) await fs.writeFile(path.join(directory, filename), contents, { flag: 'wx', mode: 0o600 });
  await fs.writeFile(path.join(directory, 'lab.json'), JSON.stringify({
    schema: 'chat-marks-vm-lab', version: 1, name, box, memory, cpus,
    files: Object.fromEntries(Object.entries(files).map(([key, value]) => [key, digest(value)]))
  }), { flag: 'wx', mode: 0o600 });
}
async function labs(): Promise<VmLab[]> {
  try { await checkedRoot(); } catch (e) { if ((e as NodeJS.ErrnoException).code === 'ENOENT') return []; throw e; }
  const entries = await fs.readdir(root(), { withFileTypes: true });
  const result: VmLab[] = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || !nameSchema.safeParse(entry.name).success) continue;
    try {
      const { manifest } = await openLab(entry.name);
      result.push({ name: entry.name, box: String(manifest.box), memory: Number(manifest.memory), cpus: Number(manifest.cpus), valid: true });
    } catch { result.push({ name: entry.name, valid: false }); }
  }
  return result.sort((a, b) => a.name.localeCompare(b.name));
}
async function probe(command: string): Promise<boolean> {
  return new Promise(resolve => {
    const child = spawn(command, ['--version'], { shell: false, stdio: 'ignore', windowsHide: true });
    const timer = setTimeout(() => { child.kill(); resolve(false); }, 3000);
    child.once('error', () => { clearTimeout(timer); resolve(false); });
    child.once('close', code => { clearTimeout(timer); resolve(code === 0); });
  });
}
async function doctor(): Promise<VmDoctor> {
  const checks: VmDoctor['checks'] = [];
  for (const [id, command] of [['vagrant', 'vagrant'], ['virtualbox', 'VBoxManage'], ['ansible', 'ansible-playbook']] as const) {
    const available = await probe(command);
    checks.push({ id, available, ...(!available ? { reason: 'not-found-or-failed' } : {}) });
  }
  return { ready: checks.every(item => item.available), checks };
}
async function view(): Promise<VmView> {
  return { labs: await labs(), doctor: await doctor(), jobs: [...jobs.values()].map(job => ({ ...job.state, log: [...job.state.log] })) };
}
function run(name: string, action: VmAction, directory: string, dryRun: boolean, notify: (job: VmJob) => void): VmJob {
  if (busy.has(name)) throw new Error('Another operation is already running for this VM.');
  const state: VmJob = { name, action, running: !dryRun, log: [] };
  if (dryRun) { state.log.push(`DRY RUN: vagrant ${actions[action].join(' ')}`); state.exitCode = 0; jobs.set(name, { state, process: null, timer: null }); notify(state); return state; }
  busy.add(name);
  const env = { ...process.env };
  for (const key of Object.keys(env)) if (key.startsWith('VAGRANT_')) delete env[key];
  const child = spawn('vagrant', actions[action], { cwd: directory, shell: false, env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
  const entry: { state: VmJob; process: ChildProcess | null; timer: NodeJS.Timeout | null } = { state, process: child, timer: null };
  jobs.set(name, entry);
  const append = (value: string): void => {
    // Bound both each chunk and the retained stream. Never send terminal control codes.
    const safe = value.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '').replace(/[\x00-\x08\x0e-\x1f]/g, '').slice(0, 4096);
    state.log.push(safe);
    if (state.log.length > 160) state.log.splice(0, state.log.length - 160);
    notify(state);
  };
  child.stdout.on('data', data => append(String(data)));
  child.stderr.on('data', data => append(String(data)));
  let done = false;
  const finish = (code: number): void => {
    if (done) return;
    done = true;
    if (entry.timer) clearTimeout(entry.timer);
    state.running = false;
    state.exitCode = code;
    entry.process = null;
    busy.delete(name);
    notify(state);
  };
  child.once('error', () => { append('Vagrant could not start. Check installation.'); finish(1); });
  child.once('close', code => finish(code ?? 1));
  entry.timer = setTimeout(() => { append('Operation timed out and was terminated.'); child.kill(); finish(1); }, 15 * 60 * 1000);
  notify(state);
  return state;
}
export function registerVmsIpc(getWindow: () => BrowserWindow | null): void {
  const notify = (state: VmJob): void => {
    const target = getWindow();
    if (target && !target.isDestroyed()) target.webContents.send('marksVms:event', { ...state, log: [...state.log] });
  };
  ipcMain.handle('marksVms:request', async (event, payload: unknown) => {
    try {
      const target = getWindow();
      if (markspanelAccessBlocked() || !target || target.isDestroyed() || event.sender !== target.webContents || event.senderFrame !== target.webContents.mainFrame) throw new Error('Unauthorized window.');
      const data = request.parse(payload);
      if (data.action === 'view') return { ok: true, data: await view() };
      if (busy.has(data.name) && data.action !== 'cancel') throw new Error('VM operation in progress.');
      if (data.action === 'init') { await init(data.name, data.box, data.memory, data.cpus); return { ok: true, data: await view() }; }
      if (data.action === 'cancel') {
        const active = jobs.get(data.name);
        if (!active?.state.running || !active.process) throw new Error('No running operation.');
        active.process.kill();
        return { ok: true, data: true };
      }
      const { directory } = await openLab(data.name);
      if (data.op === 'destroy' && data.confirmation !== data.name) throw new Error('Enter the exact VM name to destroy.');
      if (!data.dryRun && !(await probe('vagrant'))) throw new Error('Install Vagrant before running VM actions.');
      return { ok: true, data: run(data.name, data.op, directory, data.dryRun === true, notify) };
    } catch (error) {
      return { ok: false, error: error instanceof z.ZodError ? 'Invalid VM request.' : error instanceof Error ? error.message : 'VM action failed.' };
    }
  });
}
