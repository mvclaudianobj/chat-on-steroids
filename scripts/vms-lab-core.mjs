import { createHash } from 'node:crypto';
import { spawn } from 'node:child_process';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';

// Standalone first phase of item N. No IPC, secrets, or application profiles are touched.
export const LAB_SCHEMA = 'chat-marks-vm-lab';
export const LAB_VERSION = 1;
export const DEFAULT_BOX = 'bento/ubuntu-24.04';
const NAME = /^[a-z](?:[a-z0-9-]{0,38}[a-z0-9])?$/;
const BOX = /^[a-zA-Z0-9][a-zA-Z0-9._/-]{1,120}$/;
const ACTIONS = Object.freeze({
  status: ['status'],
  up: ['up', '--provider=virtualbox'],
  halt: ['halt'],
  provision: ['provision'],
  destroy: ['destroy', '--force']
});

function fail(message) {
  throw new Error(message);
}

export function validateLabName(name) {
  if (typeof name !== 'string' || !NAME.test(name)) {
    fail('VM name must be 1-40 lowercase letters, digits or hyphens; start with a letter and end with a letter/digit.');
  }
  return name;
}

export function validateBox(box) {
  if (typeof box !== 'string' || !BOX.test(box) || box.includes('..') || box.includes('//')) {
    fail('Invalid Vagrant box identifier.');
  }
  return box;
}

export function validateResources(memory, cpus) {
  if (!Number.isInteger(memory) || memory < 512 || memory > 32768) fail('Memory must be an integer from 512 to 32768 MiB.');
  if (!Number.isInteger(cpus) || cpus < 1 || cpus > 16) fail('CPUs must be an integer from 1 to 16.');
  return { memory, cpus };
}

export function defaultLabRoot() {
  const dataHome = process.env.XDG_DATA_HOME && path.isAbsolute(process.env.XDG_DATA_HOME)
    ? process.env.XDG_DATA_HOME
    : path.join(os.homedir(), '.local', 'share');
  return path.join(dataHome, 'chat-marks', 'vms');
}

function resolveRoot(root) {
  const target = root ?? defaultLabRoot();
  if (typeof target !== 'string' || !path.isAbsolute(target)) fail('Lab root must be an absolute path.');
  if (path.parse(target).root === path.resolve(target)) fail('Do not use a filesystem root as a lab root.');
  return path.resolve(target);
}

async function labRoot(root, create) {
  const base = resolveRoot(root);
  if (create) await fs.mkdir(base, { recursive: true, mode: 0o700 });
  let stat;
  try {
    stat = await fs.lstat(base);
  } catch (error) {
    if (!create && error?.code === 'ENOENT') return null;
    throw error;
  }
  if (!stat.isDirectory() || stat.isSymbolicLink()) fail('Lab root must be a real directory, not a symlink.');
  return base;
}

function vagrantfile(name, box, memory, cpus) {
  return [
    '# Generated by Chat Marks VM lab. No host-folder sharing or forwarded app ports.',
    'Vagrant.configure("2") do |config|',
    '  config.vm.box = "' + box + '"',
    '  config.vm.hostname = "' + name + '.test"',
    '  config.vm.synced_folder ".", "/vagrant", disabled: true',
    '  config.ssh.insert_key = true',
    '  config.vm.provider "virtualbox" do |provider|',
    '    provider.name = "marks-' + name + '"',
    '    provider.memory = ' + memory,
    '    provider.cpus = ' + cpus,
    '  end',
    '  config.vm.provision "ansible" do |ansible|',
    '    ansible.playbook = "site.yml"',
    '  end',
    'end',
    ''
  ].join('\n');
}

function playbook() {
  return [
    '---',
    '- name: Verify isolated Chat Marks guest',
    '  hosts: all',
    '  gather_facts: false',
    '  tasks:',
    '    - name: Confirm Ansible can reach the guest',
    '      ansible.builtin.ping: {}',
    ''
  ].join('\n');
}

function digest(content) {
  return createHash('sha256').update(content, 'utf8').digest('hex');
}

export async function createLab({ name, root, box = DEFAULT_BOX, memory = 2048, cpus = 2 }) {
  validateLabName(name);
  validateBox(box);
  validateResources(memory, cpus);
  const base = await labRoot(root, true);
  const directory = path.join(base, name);
  // mkdir without recursive prevents overwriting an existing VM, including an empty directory.
  await fs.mkdir(directory, { mode: 0o700 });
  const vf = vagrantfile(name, box, memory, cpus);
  const yml = playbook();
  const manifest = {
    schema: LAB_SCHEMA,
    version: LAB_VERSION,
    name, box, memory, cpus,
    files: { Vagrantfile: digest(vf), 'site.yml': digest(yml) }
  };
  // Write-only bootstrap: no credentials, host SSH keys, or existing folders are read.
  // If an IO failure leaves a partial directory, preserve it for inspection; never remove user data.
  await fs.writeFile(path.join(directory, 'Vagrantfile'), vf, { flag: 'wx', mode: 0o600 });
  await fs.writeFile(path.join(directory, 'site.yml'), yml, { flag: 'wx', mode: 0o600 });
  await fs.writeFile(path.join(directory, 'lab.json'), JSON.stringify(manifest, null, 2) + '\n', { flag: 'wx', mode: 0o600 });
  return { directory, manifest };
}

async function checkedFile(directory, filename, expectedDigest) {
  const file = path.join(directory, filename);
  const stat = await fs.lstat(file);
  if (!stat.isFile() || stat.isSymbolicLink()) fail(filename + ' must be a regular file, not a symlink.');
  const content = await fs.readFile(file, 'utf8');
  if (digest(content) !== expectedDigest) {
    fail(filename + ' changed since lab creation. Review it before running Vagrant; this foundation only operates on generated templates.');
  }
}

export async function openLab({ name, root }) {
  validateLabName(name);
  const base = await labRoot(root, false);
  if (!base) fail('No VM lab root exists.');
  const directory = path.join(base, name);
  const stat = await fs.lstat(directory);
  if (!stat.isDirectory() || stat.isSymbolicLink()) fail('VM lab folder must be a real directory.');
  const manifestFile = path.join(directory, 'lab.json');
  const manifestStat = await fs.lstat(manifestFile);
  if (!manifestStat.isFile() || manifestStat.isSymbolicLink()) fail('Invalid VM lab manifest.');
  const manifest = JSON.parse(await fs.readFile(manifestFile, 'utf8'));
  if (manifest.schema !== LAB_SCHEMA || manifest.version !== LAB_VERSION || manifest.name !== name) {
    fail('Unsupported or mismatched VM lab manifest.');
  }
  validateBox(manifest.box);
  validateResources(manifest.memory, manifest.cpus);
  if (!manifest.files || typeof manifest.files.Vagrantfile !== 'string' ||
      typeof manifest.files['site.yml'] !== 'string') fail('VM lab manifest is missing template checksums.');
  await checkedFile(directory, 'Vagrantfile', manifest.files.Vagrantfile);
  await checkedFile(directory, 'site.yml', manifest.files['site.yml']);
  return { directory, manifest };
}

export async function listLabs({ root } = {}) {
  const base = await labRoot(root, false);
  if (!base) return [];
  const entries = await fs.readdir(base, { withFileTypes: true });
  const labs = [];
  for (const entry of entries) {
    if (!entry.isDirectory() || !NAME.test(entry.name)) continue;
    try {
      const { manifest } = await openLab({ name: entry.name, root: base });
      labs.push({ name: entry.name, box: manifest.box, valid: true });
    } catch {
      labs.push({ name: entry.name, valid: false });
    }
  }
  return labs.sort((a, b) => a.name.localeCompare(b.name));
}

export async function executeLab({ action, name, root, dryRun = false, confirmation, runner = spawn }) {
  if (!Object.hasOwn(ACTIONS, action)) fail('Unknown VM action.');
  const { directory } = await openLab({ name, root });
  if (action === 'destroy' && confirmation !== name) {
    fail('Destruction requires --confirm-destroy followed by the exact VM name.');
  }
  const args = ACTIONS[action];
  if (dryRun) return { command: 'vagrant', args, cwd: directory, dryRun: true };
  const env = { ...process.env };
  // Ensure inherited Vagrant overrides cannot silently redirect operations to another VM.
  delete env.VAGRANT_CWD;
  delete env.VAGRANT_DOTFILE_PATH;
  return new Promise((resolve, reject) => {
    let child;
    try {
      child = runner('vagrant', args, { cwd: directory, env, shell: false, stdio: 'inherit', windowsHide: false });
    } catch (error) {
      reject(error);
      return;
    }
    child.once('error', error => {
      reject(error?.code === 'ENOENT' ? new Error('Vagrant is not installed or not on PATH. Install Vagrant, VirtualBox and Ansible first.') : error);
    });
    child.once('close', (code, signal) => {
      if (code === 0) resolve({ command: 'vagrant', args, cwd: directory, exitCode: 0 });
      else reject(new Error('Vagrant ' + action + ' exited with ' + (signal ? 'signal ' + signal : 'code ' + code) + '.'));
    });
  });
}
